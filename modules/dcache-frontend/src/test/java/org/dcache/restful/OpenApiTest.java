package org.dcache.restful;

import static java.nio.charset.StandardCharsets.UTF_8;
import static org.hamcrest.MatcherAssert.assertThat;
import static org.hamcrest.Matchers.contains;
import static org.hamcrest.Matchers.empty;
import static org.hamcrest.Matchers.hasKey;
import static org.hamcrest.Matchers.is;

import com.google.common.io.Resources;
import io.swagger.v3.jaxrs2.Reader;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.Operation;
import io.swagger.v3.oas.models.security.SecurityScheme;
import io.swagger.v3.oas.models.servers.Server;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.stream.Collectors;
import org.junit.BeforeClass;
import org.junit.Test;

/**
 * Checks the OpenAPI description of the REST API, as served at {@code /api/v1/openapi.json}.
 */
public class OpenApiTest {

    private static OpenAPI api;

    @BeforeClass
    public static void read() {
        api = new Reader(DcacheRestApplication.openApiConfiguration())
              .read(new DcacheRestApplication().getClasses());
    }

    /**
     * The operations listed in {@code swagger.json}, the description generated by swagger 1.x
     * before the move to OpenAPI 3.
     * <p>
     * {@code swagger-operations.txt} is a frozen copy of those operations. It cannot be
     * regenerated, because swagger 1.x is gone. New endpoints need no edit; delete a line only
     * when an endpoint is removed on purpose.
     */
    @Test
    public void shouldDocumentOperationsOfSwaggerJson() throws Exception {
        List<String> swagger = Resources.readLines(
              Resources.getResource(OpenApiTest.class, "swagger-operations.txt"), UTF_8);
        Set<String> documented = new HashSet<>();
        api.getPaths().forEach((path, item) -> item.readOperationsMap().keySet()
              .forEach(method -> documented.add(method + " " + path)));

        List<String> missing = swagger.stream()
              .filter(operation -> !documented.contains(operation))
              .collect(Collectors.toList());

        assertThat(missing, is(empty()));
    }

    @Test
    public void shouldDocumentReturnedEntityOfOperationListingOtherResponses() {
        Operation getCell = api.getPaths().get("/cells/{address}").getGet();

        assertThat(getCell.getResponses().get("200").getContent().get("application/json")
              .getSchema().get$ref(), is("#/components/schemas/CellData"));
    }

    @Test
    public void shouldDescribeBasicAuthentication() {
        SecurityScheme scheme = api.getComponents().getSecuritySchemes().get("basicAuth");

        assertThat(scheme.getType(), is(SecurityScheme.Type.HTTP));
        assertThat(scheme.getScheme(), is("basic"));
        assertThat(api.getPaths().get("/cells/{address}").getGet().getSecurity().get(0),
              hasKey("basicAuth"));
    }

    @Test
    public void shouldServeApiBelowApiV1() {
        assertThat(api.getServers().stream().map(Server::getUrl).collect(Collectors.toList()),
              contains("/api/v1"));
    }
}
